async def main():
    output = ROOT / 'assets/demo/narration'
    output.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(3)

    async def generate(index, scene):
        key, title, script = scene
        path = output / f'v1-{key}.mp3'
        boundaries = []
        if path.exists():
            raise RuntimeError(f'Preserve existing file: {path}')
        async with semaphore:
            voice = edge_tts.Communicate(script, 'zh-CN-YunxiNeural', rate='+8%', boundary='SentenceBoundary')
            with path.open('xb') as audio:
                async for item in voice.stream():
                    if item['type'] == 'audio':
                        audio.write(item['data'])
                    elif item['type'] == 'SentenceBoundary':
                        boundaries.append({'start': round(item['offset'] / 10000000, 3), 'text': item['text']})
        duration = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'default=nw=1:nk=1', str(path)], text=True).strip())
        print(f'{index+1:02d} {key}: {duration:.2f}s', flush=True)
        return {'id': key, 'title': title, 'text': script, 'src': '/' + path.relative_to(ROOT).as_posix(), 'duration': duration, 'captions': boundaries}

    scenes = await asyncio.gather(*(generate(i, scene) for i, scene in enumerate(SCENES)))
    total = sum(scene['duration'] for scene in scenes)
    rate = round(total / 180, 4)
    if not .8 <= rate <= 1.3:
        raise RuntimeError(f'Revise script for natural pace: {total:.2f}s, rate {rate}')
    target = ROOT / 'src/ui/demo-narration.js'
    target.write_text('// Generated by scripts/generate-demo-narration.py. Chinese synthetic booth narration.\n'
                      + 'export const NARRATION_RATE = ' + str(rate) + ';\n'
                      + 'export const NARRATION_SCENES = ' + json.dumps(scenes, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8', newline='\n')
    print(f'Total: {total:.2f}s; playback rate: {rate}; presented duration: {total/rate:.2f}s')


if __name__ == '__main__':
    asyncio.run(main())
